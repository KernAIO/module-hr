-- Row-level security for the two new tenant tables, in the same shape as 0001 and for the same
-- reason: the API checks membership and permission first, and this is what is left when a query
-- reaches the database another way. `create policy` has no `if not exists` at all, so each one is
-- preceded by a `drop policy if exists` — without that pair, replaying this file throws, and a
-- module migration that throws stops the whole host service booting rather than only this module.
--
-- One policy per table rather than a narrower set for `sensitive_access_log`, even though that table
-- is append-only. Append-only here is the application's promise, the same way it is for `punches`
-- and `person_history`; RLS answers a different question — which workspace's rows exist at all — and
-- giving one table a different shape of policy from the other thirty-two would read as a decision
-- nobody could reconstruct.
alter table "mod_hr"."sensitive_access_log" enable row level security;--> statement-breakpoint
alter table "mod_hr"."sensitive_access_log" force row level security;--> statement-breakpoint
