-- Subject access, erasure and retention.
--
-- Three things, one migration, and all of it additive: new nullable columns and two new tables, so
-- the image before this one reads the schema unchanged and a rollback needs no dump.
--
-- * `people.erased_at` / `erased_by` / `erasure_reason` — the erasure tombstone. Deliberately not a
--   new member of `status`: that column carries the employment lifecycle, and overloading it makes
--   "was she still employed when this was approved" unanswerable, which is the question a payroll
--   audit asks. Widening `PersonStatus` would also be a *constructing* break on a shared contract —
--   every stored row keeps parsing and every site that builds one stops compiling.
-- * `people.erased_file_ids` — the file objects an erasure had to leave behind. `core.files.get` is
--   the only file procedure a module can reach, so clearing `photo_file_id` orphans the object;
--   recording the id is what keeps that finishable instead of losing it.
-- * `sensitive_access_log` — who read a national identity number, a birth date or a bank account.
--   Written in the same transaction as the read, in HR's own schema rather than only in
--   `mod_core.activity_events`, because that table is read behind `core.audit.view` and these fields
--   are not.
-- * `retention_settings` — how long this workspace keeps each class. One row per workspace, so
--   `workspace_id` is the primary key and "one row" is the database's promise rather than a
--   convention. Every horizon is null until somebody sets one.
--
-- Generated by drizzle-kit from `src/server/schema.ts` and then given `if not exists` on every
-- statement, plus the two RLS blocks drizzle cannot express. Drizzle keys applied migrations by
-- content hash, so editing any file in this folder replays every file in it: a statement here that
-- cannot run twice takes down every module in the host service at boot, not just this one.
